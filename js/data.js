// Helper to get or initialize stored data
function getAppDatabase() {
  const storedConfig = localStorage.getItem("ERPH_CONFIG_SKRANGGU");
  const storedSchedule = localStorage.getItem("ERPH_SCHEDULE_SKRANGGU");
  const storedRph = localStorage.getItem("ERPH_RPH_LIST_SKRANGGU");
  const storedTeachers = localStorage.getItem("ERPH_TEACHERS_SKRANGGU");

  return {
    config: storedConfig ? JSON.parse(storedConfig) : ERPH_CONFIG,
    schedule: storedSchedule ? JSON.parse(storedSchedule) : INITIAL_SCHEDULE,
    rphList: storedRph ? JSON.parse(storedRph) : INITIAL_RPH_LIST,
    teachers: storedTeachers ? JSON.parse(storedTeachers) : TEACHERS_DATA,
    subjects: SUBJECTS_DATA,
    darjahList: DARJAH_DATA
  };
}

function saveAppDatabase(db) {
  if (db.config) localStorage.setItem("ERPH_CONFIG_SKRANGGU", JSON.stringify(db.config));
  if (db.schedule) localStorage.setItem("ERPH_SCHEDULE_SKRANGGU", JSON.stringify(db.schedule));
  if (db.rphList) localStorage.setItem("ERPH_RPH_LIST_SKRANGGU", JSON.stringify(db.rphList));
  if (db.teachers) localStorage.setItem("ERPH_TEACHERS_SKRANGGU", JSON.stringify(db.teachers));
}

function resetAppDatabaseToDefault() {
  localStorage.setItem("ERPH_CONFIG_SKRANGGU", JSON.stringify(ERPH_CONFIG));
  localStorage.setItem("ERPH_SCHEDULE_SKRANGGU", JSON.stringify(INITIAL_SCHEDULE));
  localStorage.setItem("ERPH_RPH_LIST_SKRANGGU", JSON.stringify(INITIAL_RPH_LIST));
  localStorage.setItem("ERPH_TEACHERS_SKRANGGU", JSON.stringify(TEACHERS_DATA));
}
